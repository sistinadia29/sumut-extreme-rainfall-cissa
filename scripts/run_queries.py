"""
Jalankan semua query di sql/queries.sql, cetak ringkasannya, dan simpan:
    outputs/tables/<nama_query>.csv   hasil tiap query
    outputs/tables/RESULTS.md         semua hasil dalam satu halaman Markdown
                                       (tampil rapi di GitHub)

Contoh:
    python scripts/run_queries.py              # semua query
    python scripts/run_queries.py q05          # hanya query yang namanya mengandung "q05"
"""

import re
import sys
from pathlib import Path

import duckdb
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from sumut_rain import PROJECT_ROOT, load_config, project_path  # noqa: E402


def parse_queries(sql_text: str) -> list[dict]:
    """Pecah file SQL menjadi blok berdasarkan baris '-- name:'."""
    blocks = re.split(r"^-- name:\s*", sql_text, flags=re.MULTILINE)[1:]
    queries = []
    for block in blocks:
        name, _, body = block.partition("\n")
        m = re.search(r"^-- question:\s*(.+)$", body, flags=re.MULTILINE)
        sql = re.sub(r"^--.*$", "", body, flags=re.MULTILINE).strip().rstrip(";")
        queries.append({"name": name.strip(), "question": m.group(1).strip() if m else "", "sql": sql})
    return queries


def to_markdown(df: pd.DataFrame, max_rows: int = 15) -> str:
    """Tabel Markdown sederhana tanpa dependensi tambahan."""
    shown = df.head(max_rows)
    lines = ["| " + " | ".join(map(str, shown.columns)) + " |",
             "|" + "|".join("---" for _ in shown.columns) + "|"]
    for _, row in shown.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    if len(df) > max_rows:
        lines.append(f"\n*... {len(df) - max_rows} baris lainnya ada di file CSV.*")
    return "\n".join(lines)


def main() -> None:
    cfg = load_config()
    db = project_path(cfg["paths"]["processed"]) / "sumut_climate.duckdb"
    if not db.exists():
        sys.exit("Database belum ada. Jalankan build_database.py dulu.")
    out_dir = project_path("outputs/tables")

    queries = parse_queries((PROJECT_ROOT / "sql" / "queries.sql").read_text(encoding="utf-8"))
    if len(sys.argv) > 1:
        queries = [q for q in queries if sys.argv[1] in q["name"]]

    con = duckdb.connect(str(db), read_only=True)
    md = ["# Query results\n",
          "Generated by `scripts/run_queries.py` from `sql/queries.sql` "
          "(CHIRPS v2.0, North Sumatra, 1981-2025).\n"]
    pd.set_option("display.width", 160)
    for q in queries:
        df = con.execute(q["sql"]).df()
        df.to_csv(out_dir / f"{q['name']}.csv", index=False)
        print(f"\n=== {q['name']}: {q['question']}")
        print(df.head(10).to_string(index=False))
        md += [f"\n## {q['name']}\n", f"**{q['question']}**\n",
               "```sql\n" + q["sql"] + "\n```\n", to_markdown(df) + "\n"]
    con.close()

    (out_dir / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nTersimpan: {out_dir} ({len(queries)} query, ringkasan di RESULTS.md)")


if __name__ == "__main__":
    main()
